/**
 * Writes src/generated/qr.ts: the QR code (SVG path) for the public app address, used by the
 * printable poster and handbook stickers (/poster). Rerun if the address changes:
 *   npm run make-qr -- https://new.address/
 * The printed address stays plain; the code itself adds LINE's ?openExternalBrowser=1 (src/lib/line.ts).
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import QRCode from "qrcode";
import { withOpenExternal } from "../src/lib/line";

const url = process.argv[2] ?? "https://phimai-hospital.github.io/";
// the code carries LINE's open-in-browser parameter, so LINE's own scanner opens Safari/Chrome; cameras ignore it
const qrUrl = withOpenExternal(url);
// error level M: still scans with a scuff or a fold, keeps the code small enough for a sticker
const svg = await QRCode.toString(qrUrl, { type: "svg", errorCorrectionLevel: "M", margin: 0 });
const viewBox = /viewBox="([^"]+)"/.exec(svg)![1];
// the dark modules are the stroked path (the other path is the white background)
const path = /<path stroke="[^"]+" d="([^"]+)"/.exec(svg)![1];
const out = `// GENERATED by scripts/make-qr.ts — do not edit by hand.
export const appUrl = ${JSON.stringify(url)};
export const qrUrl = ${JSON.stringify(qrUrl)};
export const qrViewBox = ${JSON.stringify(viewBox)};
export const qrPath = ${JSON.stringify(path)};
`;
writeFileSync(join(import.meta.dirname, "../src/generated/qr.ts"), out);
console.log(`QR for ${qrUrl} (${viewBox})`);
