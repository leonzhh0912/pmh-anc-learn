/**
 * Builds docs/REVIEW-PACK.md: one checklist section per lesson (and its video)
 * for PMH clinical reviewers — what to review, who should review it, every note
 * the author left (additions beyond the handbook, HANDBOOK ISSUEs), and the
 * sign-off fields to fill in.
 *   npm run review-pack
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const read = (p: string) => JSON.parse(readFileSync(p, "utf8"));
const lessonsDir = join(root, "content/lessons");
const scriptsDir = join(root, "content/video-scripts");
const curriculum: { lessonId: string; reviewRequirements: string[]; pmhClarificationNeeded: string[]; release: string }[] =
  read(join(root, "content/curriculum.json"));
const sections: { id: string; title: string }[] = read(join(root, "content/sections.json"));

const printed = (p: number) => (p === 67 ? "สรุปท้ายเล่ม" : p <= 2 ? "ปก" : String(p - 2));
const lessons = readdirSync(lessonsDir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => read(join(lessonsDir, f)))
  .sort(
    (a, b) =>
      sections.findIndex((s) => s.id === a.sectionId) - sections.findIndex((s) => s.id === b.sectionId) ||
      a.id.localeCompare(b.id, "en", { numeric: true }),
  );

const out: string[] = [
  "# Clinical review pack",
  "",
  "_Generated by `cd app && npm run review-pack`. Do not edit by hand. Regenerate after content changes._",
  "",
  "How to use: open each lesson in the app (staging or `npm run dev`, path `/lesson/<id>`), watch its video, and",
  "check every statement against the cited page of the paper handbook. Resolve every note below, then record the",
  "reviewer name and date (see CONTENT_REVIEW.md). Notes marked **HANDBOOK ISSUE** need a decision from PMH.",
  "",
  `Lessons in this pack: ${lessons.length}`,
  "",
];

for (const l of lessons) {
  const plan = curriculum.find((c) => c.lessonId === l.id);
  const videoStep = l.steps.find((s: { type: string }) => s.type === "video") as { videoId: string } | undefined;
  const scriptPath = videoStep ? join(scriptsDir, `${videoStep.videoId}.json`) : null;
  const script = scriptPath && existsSync(scriptPath) ? read(scriptPath) : null;
  const quiz = l.steps.find((s: { type: string }) => s.type === "quiz") as { questions: unknown[] } | undefined;
  const issues = (l.editorial.reviewNotes as string[]).filter((n) => /HANDBOOK ISSUE/i.test(n)).length;

  out.push(
    `## ${l.id} — ${l.title}`,
    "",
    `- Handbook: printed page ${l.handbookRef.pdfPages.map(printed).join(", ")} (official PDF p${l.handbookRef.pdfPages.join(", p")})`,
    `- Status: **${l.editorial.status}** · version ${l.version} · clinical risk **${l.editorial.clinicalRisk}** · release ${plan?.release ?? "?"}`,
    `- Content: ${l.steps.length} steps, end-of-lesson quiz with ${quiz?.questions.length ?? 0} questions${script ? `, video ${script.id} (v${script.version})` : ", no video yet"}`,
    `- Handbook issues to decide: ${issues}`,
    "",
    "**Who should review**",
    "",
    ...(plan?.reviewRequirements ?? ["(see curriculum)"]).map((r) => `- [ ] ${r}`),
    "",
    "**Author notes to resolve (lesson)**",
    "",
    ...(l.editorial.reviewNotes as string[]).map((n) => `- [ ] ${n}`),
    "",
  );
  if (script) {
    out.push(
      "**Video notes to resolve**",
      "",
      ...(script.editorial.reviewNotes as string[]).map((n) => `- [ ] ${n}`),
      "",
    );
  }
  out.push(
    "**Sign-off**",
    "",
    "| Role | Name | Date | Decision |",
    "|---|---|---|---|",
    "| Clinical reviewer |  |  | approve / changes needed |",
    "| Thai language / pronunciation |  |  | approve / changes needed |",
    "",
    "---",
    "",
  );
}

writeFileSync(join(root, "docs/REVIEW-PACK.md"), out.join("\n"));
console.log(`docs/REVIEW-PACK.md: ${lessons.length} lessons`);
