#!/usr/bin/env node
/**
 * Writes src/generated/videos.ts: one entry per video script that has a
 * narration timing file. Run automatically at the end of `npm run narrate`;
 * run by hand with `node scripts/registry.mjs`.
 */
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const videoRoot = resolve(here, "..");
const scriptsDir = resolve(videoRoot, "../content/video-scripts");

// content/videos/<id>.json is the published record; a PMH reviewer's approval is recorded there
const published = (id) => existsSync(resolve(videoRoot, "../content/videos", `${id}.json`));

export function writeRegistry() {
  const ids = readdirSync(scriptsDir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.slice(0, -5))
    .filter((id) => existsSync(join(videoRoot, "src/generated", `${id}.timing.json`)))
    .sort();
  const v = (id) => id.replace(/[^A-Za-z0-9]/g, "_");
  const lines = [
    "// GENERATED by scripts/registry.mjs — do not edit by hand.",
    'import type { Published, Timing, VideoScript } from "../lesson/types";',
    ...ids.flatMap((id) => [
      `import s_${v(id)} from "../../../content/video-scripts/${id}.json";`,
      `import t_${v(id)} from "./${id}.timing.json";`,
      ...(published(id) ? [`import p_${v(id)} from "../../../content/videos/${id}.json";`] : []),
    ]),
    "",
    "export const generatedVideos: { script: VideoScript; timing: Timing; published: Published | null }[] = [",
    ...ids.map(
      (id) =>
        `  { script: s_${v(id)} as VideoScript, timing: t_${v(id)} as Timing, published: ${published(id) ? `p_${v(id)} as Published` : "null"} },`,
    ),
    "];",
    "",
  ];
  writeFileSync(join(videoRoot, "src/generated/videos.ts"), lines.join("\n"));
  return ids;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log("registered:", writeRegistry().join(", "));
}
